#!/bin/bash
# Builds the Company Engine Mac app: a signed .app bundle, from the Command Line Tools only.
#   build.sh --dev --origin-port <3300-65535> --out <dir>
#   build.sh --install [--engine-root <abs path>]
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
CHECKOUT="$(cd "$HERE/../.." && pwd -P)"

die() { echo "build.sh: $*" >&2; exit 1; }

MODE="" PORT="" OUT="" ROOT="" ROOT_GIVEN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dev) MODE=dev; shift ;;
    --install) MODE=install; shift ;;
    --origin-port) [ $# -ge 2 ] || die "--origin-port needs a number."; PORT="$2"; shift 2 ;;
    --out) [ $# -ge 2 ] || die "--out needs a folder."; OUT="$2"; shift 2 ;;
    --engine-root) [ $# -ge 2 ] || die "--engine-root needs a path."; ROOT="$2"; ROOT_GIVEN=1; shift 2 ;;
    *) die "unknown option: $1" ;;
  esac
done
[ -n "$MODE" ] || die "say --dev or --install."

if [ "$MODE" = dev ]; then
  [ "$ROOT_GIVEN" = 0 ] || die "a development build never takes --engine-root."
  [ -n "$OUT" ] || die "a development build needs --out <dir>."
  [ -n "$PORT" ] || die "a development build needs --origin-port <port>."
  case "$PORT" in ''|*[!0-9]*) die "the port must be a number." ;; esac
  [ ${#PORT} -le 5 ] || die "the port must be 3300 to 65535."
  if [ "$PORT" -lt 3300 ] || [ "$PORT" -gt 65535 ] || [ "$PORT" = 5000 ] || [ "$PORT" = 5432 ] || [ "$PORT" = 7000 ] || [ "$PORT" = 8120 ]; then
    die "the port must be 3300 to 65535, and not 5000, 5432, 7000 or 8120."
  fi
  FLAVOR=dev; APP_NAME="Company Engine Dev"; BUNDLE_ID="local.uuu.company-engine.dev"
  ENGINE_ROOT=""
  mkdir -p "$OUT"; OUT="$(cd "$OUT" && pwd -P)"
  DEST="$OUT/$APP_NAME.app"
else
  [ -z "$PORT" ] || die "an installed build always uses port 3200."
  [ -z "$OUT" ] || die "an installed build goes to ~/Applications; --out is for development builds."
  PORT=3200
  FLAVOR=release; APP_NAME="Company Engine"; BUNDLE_ID="local.uuu.company-engine"
  if [ "$ROOT_GIVEN" = 1 ]; then ENGINE_ROOT="$ROOT"; else ENGINE_ROOT="$CHECKOUT"; fi
  case "$ENGINE_ROOT" in /*) ;; *) die "--engine-root must be an absolute path." ;; esac
  if [ -n "$(git -C "$CHECKOUT" status --porcelain -- engine/mac)" ]; then
    die "engine/mac has changes that are not committed. Commit them, then build."
  fi
  DEST="$HOME/Applications/$APP_NAME.app"
fi

case "$ENGINE_ROOT" in *[\"\\$'\n']*) die "the engine root has a character that is not allowed." ;; esac

VERSION="$(head -n 1 "$HERE/VERSION" | tr -d '[:space:]')"
[ -n "$VERSION" ] || die "VERSION is empty."
BUILD="$(git -C "$CHECKOUT" rev-list --count HEAD -- engine/mac)"

cat > "$HERE/Sources/EngineShell/Build/BuildConstants.swift" <<SWIFT
// Generated by build.sh. Not committed.
public enum BuildConstants {
    public static let homePort = $PORT
    public static let engineRoot = "$ENGINE_ROOT"
    public static let flavor = "$FLAVOR"
    public static let version = "$VERSION"
    public static let build = "$BUILD"
}
SWIFT

echo "Building $APP_NAME $VERSION (build $BUILD) for port $PORT."
cd "$HERE"
swift build -c release --product CompanyEngine
BIN="$(swift build -c release --product CompanyEngine --show-bin-path)/CompanyEngine"
[ -x "$BIN" ] || die "the build made no program."

rm -rf "$DEST"
mkdir -p "$DEST/Contents/MacOS" "$DEST/Contents/Resources"
sed -e "s|@BUNDLE_ID@|$BUNDLE_ID|" -e "s|@APP_NAME@|$APP_NAME|g" \
    -e "s|@VERSION@|$VERSION|" -e "s|@BUILD@|$BUILD|" \
    "$HERE/Resources/Info.plist.in" > "$DEST/Contents/Info.plist"
printf 'APPL????' > "$DEST/Contents/PkgInfo"
cp "$BIN" "$DEST/Contents/MacOS/CompanyEngine"
cp "$HERE/Resources/AppIcon.icns" "$DEST/Contents/Resources/AppIcon.icns"

plutil -lint "$DEST/Contents/Info.plist" >/dev/null
codesign --force --options runtime --sign - "$DEST"
codesign --verify --strict "$DEST"
echo "Signed and checked."
echo "$DEST"
